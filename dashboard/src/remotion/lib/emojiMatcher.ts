// Map de recherche rapide O(1)
const EMOJI_SEARCH_INDEX = new Map<string, string>();

function initializeEmojiIndex() {
    if (EMOJI_SEARCH_INDEX.size > 0) return; // Déjà initialisé

    // A. Charger la bibliothèque emojilib (mots-clés)
    for (const [emoji, keywords] of Object.entries(emojilib)) {
        for (const keyword of keywords) {
            const cleanKeyword = normalizeWord(keyword);
            if (cleanKeyword && !EMOJI_SEARCH_INDEX.has(cleanKeyword)) {
                EMOJI_SEARCH_INDEX.set(cleanKeyword, emoji);
            }
        }
    }

    // B. Injecter vos mots personnalisés (ils écrasent emojilib si conflit)
    for (const [word, emoji] of Object.entries(CUSTOM_OVERRIDE_MAP)) {
        EMOJI_SEARCH_INDEX.set(normalizeWord(word), emoji);
    }
}

// Initialisation immédiate
initializeEmojiIndex();

/**
 * Fonction principale à appeler dans votre composant
 */
export const getEmojiForWord = (rawWord: string): string | null => {
    if (!rawWord) return null;

    const clean = normalizeWord(rawWord);
    if (clean.length <= 2) return null; // Ignorer les mots trop courts ("le", "un", "de", "it")

    return EMOJI_SEARCH_INDEX.get(clean) ?? null;
};