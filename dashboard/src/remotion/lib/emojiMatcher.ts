// 1. Nettoyer et réduire le mot à sa forme racine (Français / Anglais basique)
export function normalizeWord(word: string): string {
    return word
        .toLowerCase()
        .trim()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "") // Supprime les accents (ex: "brûlant" -> "brulant")
        .replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?"'…]/g, "") // Supprime la ponctuation
        .replace(/(s|x|es|e)$/gi, ""); // Supprime les marques du pluriel / féminin simples
}

